#!/usr/bin/env bash
set -euo pipefail

# Cloudflare Pages build-time Supabase routing.
# Local development keeps the checked-in config unchanged.
if [[ "${CF_PAGES:-}" != "1" ]]; then
  echo "Cloudflare Pages environment not detected; keeping local Supabase config."
  exit 0
fi

branch="${CF_PAGES_BRANCH:-}"
if [[ -z "$branch" ]]; then
  echo "ERROR: CF_PAGES_BRANCH is missing; refusing to build with an unknown backend." >&2
  exit 1
fi

if [[ "$branch" == "main" ]]; then
  expected_url="https://pzymiesazmpyvnfvsbsc.supabase.co"
  environment_name="production"
else
  expected_url="https://ivatvkfrtifgfheeaelj.supabase.co"
  environment_name="preview/staging"
fi

# Refresh browser caches for Update 2.6.1 authentication and learning-data initialization while preserving U2.7.0 UI assets.
if [[ -f index.html ]]; then
  sed -i -E 's#(account-deletion[.]js)([?]v=[^"]*)?#\1?v=2.6.0-r5#g' index.html
  sed -i -E 's#(daily-learning[.]js)([?]v=[^"]*)?#\1?v=2.7.0-r7#g' index.html
  sed -i -E 's#(flashcards[.]js)([?]v=[^"]*)?#\1?v=2.6.1-r1#g' index.html
  sed -i -E 's#(lessons-ui[.]css)([?]v=[^"]*)?#\1?v=2.7.0-r6#g' index.html
  if ! grep -q 'permanent-lesson-confirmation.js' index.html; then
    sed -i 's#</body>#<script src="permanent-lesson-confirmation.js?v=2.7.0-r3"></script></body>#' index.html
  fi
  if ! grep -q 'lesson-topic-highlights.js' index.html; then
    sed -i 's#</body>#<script src="lesson-topic-highlights.js?v=2.7.0-r4"></script></body>#' index.html
  fi
fi

: "${SWIFT_SUPABASE_URL:?Set SWIFT_SUPABASE_URL in the matching Cloudflare Pages environment}"
: "${SWIFT_SUPABASE_PUBLISHABLE_KEY:?Set SWIFT_SUPABASE_PUBLISHABLE_KEY in the matching Cloudflare Pages environment}"

if [[ "$SWIFT_SUPABASE_URL" != "$expected_url" ]]; then
  echo "ERROR: $environment_name deployment expected $expected_url but received a different Supabase URL." >&2
  echo "Refusing to deploy to prevent cross-environment data access." >&2
  exit 1
fi

if [[ ! "$SWIFT_SUPABASE_PUBLISHABLE_KEY" =~ ^sb_publishable_[A-Za-z0-9_-]+$ ]]; then
  echo "ERROR: SWIFT_SUPABASE_PUBLISHABLE_KEY is missing or is not a Supabase publishable key." >&2
  exit 1
fi

cat > supabase-config.js <<EOF
// Generated by build.sh for this Cloudflare Pages deployment.
// Do not edit this generated file in the build output.
window.SWIFT_SUPABASE_CONFIG = {
  url: "$SWIFT_SUPABASE_URL",
  anonKey: "$SWIFT_SUPABASE_PUBLISHABLE_KEY"
};
EOF

echo "Configured SwiftDictionary for the $environment_name Supabase project."

# Preserve anonymous saved words in both production and preview builds.
# Account deletion is loaded explicitly after the main app script in index.html.
cat >> supabase-config.js <<'EOF'
try {
  if (!localStorage.getItem("swiftdictionary-anonymous-saved")) {
    const legacy = localStorage.getItem("swiftdictionary-saved");
    if (legacy) localStorage.setItem("swiftdictionary-anonymous-saved", legacy);
  }
} catch {}
EOF
