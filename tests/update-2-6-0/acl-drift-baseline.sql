-- Synthetic pre-U2.6.0 ACL state for isolated migration regression tests.
-- All objects and grants are disposable local-only test fixtures.

CREATE TABLE public.daily_activity_sessions (
  id bigint generated by default as identity primary key,
  user_id uuid not null,
  status text not null default 'in_progress'
);
ALTER TABLE public.daily_activity_sessions ENABLE ROW LEVEL SECURITY;
CREATE POLICY "test owners can manage sessions"
ON public.daily_activity_sessions FOR ALL TO authenticated
USING ((select auth.uid()) = user_id)
WITH CHECK ((select auth.uid()) = user_id);

GRANT ALL PRIVILEGES ON TABLE public.daily_activity_sessions TO anon, authenticated;
GRANT ALL PRIVILEGES ON SEQUENCE public.daily_activity_sessions_id_seq TO anon, authenticated;

-- Reproduce production's anonymous plan-limit SELECT grant.
GRANT SELECT ON TABLE public.learning_plan_limits TO anon;

-- Reproduce anonymous access on the three identity sequences before hardening.
GRANT USAGE, SELECT, UPDATE ON SEQUENCE
  public.learning_activity_log_id_seq,
  public.lesson_progress_id_seq,
  public.lesson_practice_results_id_seq
TO anon;

CREATE OR REPLACE FUNCTION public.guard_daily_activity_session_update()
RETURNS trigger LANGUAGE plpgsql SET search_path = ''
AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;
GRANT EXECUTE ON FUNCTION public.guard_daily_activity_session_update()
TO PUBLIC, anon, authenticated;
