-- Synthetic Daily Learning session objects for disposable ACL regression tests.
-- The table/function exist before the initial U2.6.0 migration, as they do in
-- the live schema. The separate ACL drift fixture adds production-like grants.

CREATE TABLE public.daily_activity_sessions (
  id bigint generated by default as identity primary key,
  user_id uuid not null,
  status text not null default 'in_progress',
  updated_at timestamptz not null default now()
);
ALTER TABLE public.daily_activity_sessions ENABLE ROW LEVEL SECURITY;
CREATE POLICY "test owners can manage sessions"
ON public.daily_activity_sessions FOR ALL TO authenticated
USING ((select auth.uid()) = user_id)
WITH CHECK ((select auth.uid()) = user_id);

CREATE OR REPLACE FUNCTION public.guard_daily_activity_session_update()
RETURNS trigger LANGUAGE plpgsql SET search_path = ''
AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;

CREATE TRIGGER guard_daily_activity_session_update
BEFORE UPDATE ON public.daily_activity_sessions
FOR EACH ROW EXECUTE FUNCTION public.guard_daily_activity_session_update();

GRANT SELECT, INSERT, UPDATE ON TABLE public.daily_activity_sessions TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.daily_activity_sessions_id_seq TO authenticated;
GRANT EXECUTE ON FUNCTION public.guard_daily_activity_session_update()
TO PUBLIC, anon, authenticated;

-- Match the audited Singapore staging baseline: plan-limit configuration is
-- readable by authenticated users but not by anonymous visitors.
REVOKE ALL PRIVILEGES ON TABLE public.learning_plan_limits FROM anon;
